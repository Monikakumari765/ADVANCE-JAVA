public class startwith {
    public static void main(String[] args) {

        String s = "Monika Kumari";

        System.out.println(s.startsWith("Monika"));
        System.out.println(s.startsWith("Kumari"));
        System.out.println(s.startsWith("kriti"));
        System.out.println(s.startsWith("puja kumari"));



    }
}


